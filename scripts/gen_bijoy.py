#!/usr/bin/env python3
"""Generates crates/akkhor-flow/src/bijoy_table.rs: the Bijoy (SutonnyMJ)
to Unicode table.

The table is the inverse of the Unicode to Bijoy map in the MIT licensed
`poriborton` crate (OpenBangla, Muhammad Mominul Huque), plus its vowel
sign rules, plus pieces derived from it: every conjunct key "AB" whose
value ends with the value of a known key "B" teaches the half form "A".

    python3 scripts/gen_bijoy.py PATH/TO/poriborton/src/bijoy2000.rs
"""

import os
import re
import sys
import unicodedata

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "crates", "akkhor-flow", "src", "bijoy_table.rs")

VIRAMA = "\u09cd"

# Vowel signs and marks written by poriborton's code rather than its map.
EXTRA = {
    "v": "া", "x": "ী",
    "y": "ু", "z": "ু", "“": "ু", "–": "ু",
    "~": "ূ", "‚": "ূ", "ƒ": "ূ",
    "„": "ৃ", "…": "ৃ",
    "w": "ি", "†": "ে", "‡": "ে", "ˆ": "ৈ", "‰": "ৈ",
    "Š": "ৗ",
    "¸": "গু", "ï": "শু", "û": "হু", "ü": "হৃ",
    "‘": "্তু",
    "¨": "্য", "©": "র্", "&": "্",
    "|": "।", "\\": "॥",
    # Below-base and half forms that only occur inside conjunct keys, read
    # off those keys (স্ব ¯^, স্ম ¯§, ন্ত š—, ক্ন Kè, ...).
    "^": "্ব", "£": "্ভ্র", "§": "্ম", "¿": "্ত্র", "è": "্ন", "Œ": "্ক্র",
    "œ": "্ন", "š": "ন্", "—": "্ত", "’": "্থ", "‹": "্ক",
}


def canonical(s):
    # NFC keeps ড় ঢ় য় composed in some inputs; the engine uses the
    # decomposed spelling (they are composition exclusions).
    out = []
    for c in s:
        d = {"ড়": "ড়", "ঢ়": "ঢ়", "য়": "য়"}.get(c)
        out.append(d or c)
    return "".join(out)


def parse(path):
    src = open(path, encoding="utf-8").read()
    body = src[src.index("phf_map!["):src.index("];")]
    pairs = re.findall(r'"((?:[^"\\]|\\.)*)"\s*=>\s*"((?:[^"\\]|\\.)*)"', body)
    unescape = lambda s: s.encode().decode("unicode_escape").encode("latin-1").decode("utf-8") if "\\" in s else s
    return [(unescape(u), unescape(b)) for u, b in pairs]


def main():
    pairs = parse(sys.argv[1])
    table = {}
    for uni, bij in pairs:
        uni = canonical(uni)
        if bij in table and table[bij] != uni:
            # Keep the shorter spelling (one Bijoy key, two Unicode forms).
            if len(uni) >= len(table[bij]):
                continue
        table[bij] = uni
    for k, v in EXTRA.items():
        table.setdefault(k, v)

    # Derive half forms and fola forms from conjunct keys.
    derived = {}
    for _ in range(4):
        new = {}
        for key, val in list(table.items()) + list(derived.items()):
            for cut in range(1, len(key)):
                head, tail = key[:cut], key[cut:]
                if tail in table and val.endswith(table[tail]) and len(val) > len(table[tail]):
                    guess = val[: len(val) - len(table[tail])]
                    # A below-base form (্ত্র) brings its own virama: the
                    # head is still a half form (স্).
                    if table[tail].startswith(VIRAMA) and not guess.endswith(VIRAMA):
                        guess += VIRAMA
                    if head not in table:
                        new.setdefault(head, []).append(guess)
                if head in table and val.startswith(table[head]) and len(val) > len(table[head]):
                    guess = val[len(table[head]):]
                    if table[head].endswith(VIRAMA) and not guess.startswith(VIRAMA):
                        guess = VIRAMA + guess
                    if tail not in table:
                        new.setdefault(tail, []).append(guess)
        changed = False
        # Majority vote over the keys that teach the same piece.
        for k, vals in new.items():
            if k in derived:
                continue
            ranked = sorted(set(vals), key=lambda v: -vals.count(v))
            if len(ranked) == 1 or vals.count(ranked[0]) > vals.count(ranked[1]):
                derived[k] = ranked[0]
                changed = True
        if not changed:
            break

    rows = sorted(table.items()) + sorted((k, v) for k, v in derived.items() if k not in table)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/gen_bijoy.py. Do not edit.\n")
        f.write("//\n// Derived from the `poriborton` crate (https://github.com/OpenBangla/poriborton),\n")
        f.write("// Copyright (c) Muhammad Mominul Huque, MIT License.\n\n")
        f.write("/// (Bijoy text, Unicode text), Bijoy text as decoded with Windows-1252.\n")
        f.write("pub(crate) static TABLE: &[(&str, &str)] = &[\n")
        for k, v in rows:
            kk = "".join(
                f"\\u{{{ord(c):04X}}}" if unicodedata.category(c)[0] in "CZ" else c
                for c in k.replace("\\", "\\\\").replace('"', '\\"')
            )
            vv = "".join(f"\\u{{{ord(c):04X}}}" for c in v)
            src = "derived" if k in derived and k not in table else ""
            f.write(f'    ("{kk}", "{vv}"),{" // " + src if src else ""}\n')
        f.write("];\n")
    print(f"{len(table)} entries, {len([k for k in derived if k not in table])} derived -> {OUT}")


if __name__ == "__main__":
    main()
