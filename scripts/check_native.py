#!/usr/bin/env python3
"""Checks android/Native.kt against the JNI functions the engine exports
(crates/akkhor-android/src/*.rs): every Kotlin `external fun` must have a
Rust function with the same name, argument types and return type, and every
exported Rust function must be declared in Native.kt.

With `--java DIR`, also writes dev/akkhor/Native.java into DIR: the same
declarations for a plain JVM (Bitmap becomes Object), so
android/test/NativeTest.java can call the host build of the library.

    python3 scripts/check_native.py [--java DIR]
"""

import argparse
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
KT = os.path.join(ROOT, "android", "Native.kt")
RUST = [os.path.join(ROOT, "crates", "akkhor-android", "src", f) for f in ("lib.rs", "app.rs")]

# Kotlin type -> (JNI type in Rust, Java type)
TYPES = {
    "Int": ("jint", "int"),
    "Long": ("jlong", "long"),
    "Float": ("jfloat", "float"),
    "Double": ("jdouble", "double"),
    "Boolean": ("jboolean", "boolean"),
    "String": ("jstring", "String"),
    "Bitmap": ("jobject", "Object"),
    "IntArray": ("jintArray", "int[]"),
    "LongArray": ("jlongArray", "long[]"),
    "FloatArray": ("jfloatArray", "float[]"),
    "Array<String>": ("jobjectArray", "String[]"),
    "Array<Bitmap>": ("jobjectArray", "Object[]"),
    "Unit": (None, "void"),
}


def kotlin():
    src = open(KT, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r"external fun (\w+)\(([^)]*)\)\s*(?::\s*([\w<>?]+))?", src, re.S):
        name, params, ret = m.group(1), m.group(2), (m.group(3) or "Unit")
        args = []
        for p in [p.strip() for p in params.split(",") if p.strip()]:
            pname, ptype = [x.strip() for x in p.split(":", 1)]
            args.append((pname, ptype.rstrip("?")))
        out[name] = (args, ret.rstrip("?"))
    return out


def rust():
    out = {}
    for path in RUST:
        src = open(path, encoding="utf-8").read()
        for m in re.finditer(r"fn Java_dev_akkhor_Native_(\w+)\(([^)]*)\)\s*(->\s*([\w:]+))?", src, re.S):
            params = [p.strip() for p in m.group(2).split(",") if p.strip()][2:]  # env, class
            types = [p.split(":", 1)[1].strip().replace("jni_sys::", "") for p in params]
            ret = (m.group(4) or "").replace("jni_sys::", "") or None
            out[m.group(1)] = (types, ret)
    return out


def check():
    kt, rs = kotlin(), rust()
    problems = []
    for name in sorted(set(kt) | set(rs)):
        if name not in rs:
            problems.append(f"{name}: in Native.kt, not exported by the engine")
            continue
        if name not in kt:
            problems.append(f"{name}: exported by the engine, not in Native.kt")
            continue
        (kargs, kret), (rargs, rret) = kt[name], rs[name]
        want = [TYPES[t][0] for _, t in kargs]
        if want != rargs:
            problems.append(f"{name}: arguments {want} in Native.kt, {rargs} in the engine")
        if TYPES[kret][0] != rret:
            problems.append(f"{name}: returns {TYPES[kret][0]} in Native.kt, {rret} in the engine")
    return kt, problems


def java(kt, out_dir):
    lines = ["package dev.akkhor;", "", "// Generated by scripts/check_native.py from android/Native.kt.",
             "public final class Native {",
             '    static { System.loadLibrary("akkhor"); }']
    for name, (args, ret) in sorted(kt.items()):
        params = ", ".join(f"{TYPES[t][1]} {n}" for n, t in args)
        lines.append(f"    public static native {TYPES[ret][1]} {name}({params});")
    lines.append("}")
    d = os.path.join(out_dir, "dev", "akkhor")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "Native.java"), "w", encoding="utf-8").write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--java")
    a = ap.parse_args()
    kt, problems = check()
    for p in problems:
        print(p)
    if problems:
        sys.exit(1)
    print(f"Native.kt matches the engine: {len(kt)} calls")
    if a.java:
        java(kt, a.java)


if __name__ == "__main__":
    main()
